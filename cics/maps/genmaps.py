"""Generate BMS map sources with correct column layout.
label col 1-8, op col 10, operands from col 16, continuation 'X' in col 72,
continuation lines start in col 16."""
import sys

def stmt(label, op, operands):
    out = []
    first = f"{label:<8} {op:<5} "
    parts = operands
    line = first
    for i, p in enumerate(parts):
        piece = p + ("," if i < len(parts) - 1 else "")
        if len(line) + len(piece) > 71:
            out.append(f"{line:<71}X")
            line = " " * 15
        line += piece
    out.append(line)
    return out

NAMED = []   # (name, length) of named fields, in source order


def field(name, row, col, length, attrb, initial=None, pic=None, extra=None):
    if name:
        NAMED.append((name, length))
    ops = [f"POS=({row},{col})", f"LENGTH={length}", f"ATTRB=({attrb})"]
    if pic:
        ops.append(f"PICIN='{pic}'")
    if extra:
        ops += extra
    if initial is not None:
        ops.append(f"INITIAL='{initial}'")
    return stmt(name or "", "DFHMDF", ops)

def label(row, col, text, attrb="ASKIP,NORM"):
    return field(None, row, col, len(text), attrb, text)

def symbolic(mapname, fields):
    """The symbolic map DFHMAPS would generate (TIOAPFX=YES, no DSATTS)."""
    c = ["      *" + "=" * 64 + "*",
         f"      * SYMBOLIC MAP {mapname:<8} - GENERATED BY cics/maps/genmaps.py".ljust(71) + "*",
         "      * SAME LAYOUT AS DFHMAPS OUTPUT FOR TIOAPFX=YES, NO DSATTS.     *",
         "      *" + "=" * 64 + "*",
         f"       01  {mapname}I.",
         "           02  FILLER                  PIC X(12)."]
    for n, ln in fields:
        c += [f"           02  {n + 'L':<22}  COMP PIC S9(4).",
              f"           02  {n + 'F':<22}  PIC X.",
              f"           02  FILLER REDEFINES {n}F.",
              f"               03  {n + 'A':<18}  PIC X.",
              f"           02  {n + 'I':<22}  PIC X({ln})."]
    c += [f"       01  {mapname}O REDEFINES {mapname}I.",
          "           02  FILLER                  PIC X(12)."]
    for n, ln in fields:
        c += ["           02  FILLER                  PIC X(03).",
              f"           02  {n + 'O':<22}  PIC X({ln})."]
    return "\n".join(c) + "\n"


def mapset(name, mapname, title, body):
    lines = ["*" + "-" * 70,
             f"* MAPSET {name} - {title}",
             "* GENERATED BY genmaps.py (EDIT THERE). ASSEMBLE WITH DFHMAPS.",
             "* UNTESTED: NO CICS IN THIS ENVIRONMENT - SEE cics/README.md.",
             "*" + "-" * 70]
    lines += stmt(name, "DFHMSD", ["TYPE=&SYSPARM", "MODE=INOUT", "LANG=COBOL",
                                    "STORAGE=AUTO", "CTRL=(FREEKB,FRSET)",
                                    "TIOAPFX=YES"])
    lines += stmt(mapname, "DFHMDI", ["SIZE=(24,80)", "LINE=1", "COLUMN=1"])
    lines += label(1, 1, "COREBANK", "ASKIP,BRT")
    lines += label(1, 30, title[:30], "ASKIP,BRT")
    lines += field("TRNDATE", 1, 70, 10, "ASKIP,NORM")
    lines += body
    lines += field("MSG", 23, 1, 79, "ASKIP,BRT")
    lines += label(24, 1, "ENTER=PROCESS PF3=EXIT PF5=REFRESH")
    lines += stmt("", "DFHMSD", ["TYPE=FINAL"])
    lines.append("         END")
    return "\n".join(lines) + "\n"

# each body is built right after NAMED is reset, so the field list
# for the symbolic map is exactly the named fields of that map
def start():
    NAMED.clear()
    # the title line's date field and the message line come from mapset()
    NAMED.append(("TRNDATE", 10))


bodies = {}

