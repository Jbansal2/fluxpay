#!/usr/bin/env python3
"""Build docs/PROGRAMS.md: every program with its purpose, the files it
uses, what it calls and who calls it, plus a Mermaid call graph of the
main menu and the shared posting services.

Usage: python3 tools/callgraph.py           (from the repository root)
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = sorted(glob.glob(os.path.join(ROOT, "src", "*.cbl"))
                 + glob.glob(os.path.join(ROOT, "sql", "*.cbl")))


def code_lines(path):
    for raw in open(path, errors="replace"):
        if len(raw) > 6 and raw[6] in "*/":
            continue
        yield raw[7:72]


def header_purpose(path):
    text, grab = [], False
    for raw in open(path, errors="replace"):
        m = re.match(r"\s+\* PURPOSE\s+:\s*(.*?)\s*\*$", raw.rstrip("\n"))
        if m:
            text.append(m.group(1)); grab = True; continue
        if grab:
            m = re.match(r"\s+\*\s{12}(\S.*?)\s*\*$", raw.rstrip("\n"))
            last = text[-1].rstrip()
            # stop at the end of the first sentence, before a list or a
            # table (indented lines, numbered items, "PART A -")
            if (not m or last.endswith((".", ":")) or "  " in m.group(1)
                    or re.match(r"(\d+|PART \w) -", m.group(1))):
                break
            text.append(m.group(1))
            continue
    sentence = " ".join(text)
    sentence = sentence.split(". ")[0].rstrip(".:")
    sentence = re.sub(r"\s+", " ", sentence)
    return sentence_case(sentence)


ACRONYMS = {"NACH", "CTS", "GL", "EMI", "EMIS", "TDS", "AML", "CTR", "STR", "FD",
            "RD", "SB", "KYC", "GST", "NPA", "ATM", "PIN", "OD", "API", "JSON",
            "SQL", "CRR", "SLR", "NDTL", "ALM", "BSR", "CICS", "PAN", "IFSC",
            "NEFT", "RTGS", "IMPS", "UPI", "CSV", "MIS", "EOD", "VSAM", "DB2",
            "UMRN", "CIBIL", "RBI", "LTV", "CIF", "SI", "PDF", "ID", "IDS",
            "BIN", "TRANLOG", "POSTGRESQL", "DORMANCY"}


def sentence_case(text):
    words = text.split(" ")
    out = []
    for i, w in enumerate(words):
        core = re.sub(r"[^\w]", "", w)
        if core in ACRONYMS - {"DORMANCY"} or core in PROGRAM_NAMES or "/" in w and w.upper() == w and len(core) <= 6:
            out.append(w)
        else:
            out.append(w.lower())
    result = " ".join(out)
    return result[:1].upper() + result[1:]


PROGRAM_NAMES = set()
for _p in SOURCES:
    _m = re.search(r"PROGRAM-ID\.\s+([\w-]+)", open(_p, errors="replace").read())
    if _m:
        PROGRAM_NAMES.add(_m.group(1))


programs = {}
for path in SOURCES:
    code = " ".join(code_lines(path))
    pid = re.search(r"PROGRAM-ID\.\s+([\w-]+)", code)
    if not pid:
        continue
    name = pid.group(1)
    calls = sorted(set(re.findall(r"\bCALL\s+'([\w-]+)'", code)) - {name})
    files = sorted(set(re.findall(r"ASSIGN\s+TO\s+'data/([\w.]+)'", code)))
    files = [f.replace(".DAT", "") for f in files]
    programs[name] = {"purpose": header_purpose(path), "calls": calls,
                      "files": files, "dir": os.path.basename(os.path.dirname(path))}

called_by = {n: [] for n in programs}
# RUNPGM calls its batch programs dynamically (CALL WS-PROGRAM)
runpgm = open(os.path.join(ROOT, "src", "RUNPGM.cbl")).read()
allowed = re.search(r"PGM-ALLOWED\s+VALUES(.*?)\.\s*$", runpgm, re.S | re.M)
if allowed:
    for b in re.findall(r"'([\w-]+)'", allowed.group(1)):
        called_by.setdefault(b, []).append("RUNPGM")
for n, p in programs.items():
    for c in p["calls"]:
        called_by.setdefault(c, []).append(n)

out = ["# Program catalogue", "",
       "Generated by `tools/callgraph.py` from the sources - do not edit by hand.", "",
       f"{len(programs)} programs. The menu (BANKMAIN) and the batch launcher",
       "(RUNPGM) are the only executables; everything else is a callable module.", "",
       "## Main call paths", "", "```mermaid", "graph LR"]
core = ["ACCTPOST", "GLPOST", "AMLCHK", "AUDITLOG", "TXNEXEC", "CASHUTIL"]
for n in sorted(programs):
    for c in programs[n]["calls"]:
        if c in core or n == "BANKMAIN":
            out.append(f"    {n} --> {c}")
out += ["```", "", "## Programs", "",
        "| Program | Purpose | Files | Calls | Called by |", "|---|---|---|---|---|"]
for n in sorted(programs):
    p = programs[n]
    out.append(f"| {n} | {p['purpose']} | {', '.join(p['files']) or '-'} | "
               f"{', '.join(p['calls']) or '-'} | {', '.join(sorted(called_by[n])) or '-'} |")
out.append("")
open(os.path.join(ROOT, "docs", "PROGRAMS.md"), "w").write("\n".join(out))
print(f"docs/PROGRAMS.md: {len(programs)} programs")
