def setup():
    L = []
    a = L.append
    a("//CBSETUP  JOB (CBANK),'COREBANK SETUP',CLASS=A,MSGCLASS=X,")
    a("//             NOTIFY=&SYSUID")
    a("//*" + "-" * 64 + "*")
    a("//* COREBANK - ONE-TIME ALLOCATION OF ALL DATASETS                 *")
    a("//* GENERATED BY tools/genjcl.py - EDIT THE LIST THERE.            *")
    a("//* KSDS RECORD SIZES / KEY LENGTHS ARE THE REAL COPYBOOK SIZES;   *")
    a("//* EVERY KEY STARTS AT OFFSET 0. RERUNNABLE (DELETES IGNORED).    *")
    a("//*" + "-" * 64 + "*")
    a("//DELETE   EXEC PGM=IDCAMS")
    a("//SYSPRINT DD SYSOUT=*")
    a("//SYSIN    DD *")
    for n, *_ in KSDS:
        a(f"  DELETE CBANK.PROD.{n}.KSDS CLUSTER PURGE")
    for n, *_ in SEQ:
        a(f"  DELETE CBANK.PROD.{n} NONVSAM PURGE")
    a("  SET MAXCC = 0")
    a("/*")
    a("//DEFINE   EXEC PGM=IDCAMS,COND=(0,NE)")
    a("//SYSPRINT DD SYSOUT=*")
    a("//SYSIN    DD *")
    for n, lr, kl, d, (p, s) in KSDS:
        a(f"  /* {d:<40} */")
        a(f"  DEFINE CLUSTER (NAME(CBANK.PROD.{n}.KSDS) -")
        a(f"         INDEXED KEYS({kl} 0) RECORDSIZE({lr} {lr}) -")
        a(f"         RECORDS({p} {s}) FREESPACE(20 10) -")
        a("         SHAREOPTIONS(2 3) SPEED) -")
        a(f"         DATA  (NAME(CBANK.PROD.{n}.KSDS.DATA)) -")
        a(f"         INDEX (NAME(CBANK.PROD.{n}.KSDS.INDEX))")
    a("/*")
    a("//*" + "-" * 64 + "*")
    a("//* SEQUENTIAL FILES (APPENDED WITH DISP=MOD)                      *")
    a("//*" + "-" * 64 + "*")
    a("//ALLOCSEQ EXEC PGM=IEFBR14,COND=(0,NE)")
    for n, lr, d, (p, s) in SEQ:
        a(f"//{n[:8]:<8} DD DSN=CBANK.PROD.{n},DISP=(NEW,CATLG,DELETE),")
        a(f"//            UNIT=SYSDA,SPACE=(CYL,({p},{s}),RLSE),")
        a(f"//            DCB=(RECFM=FB,LRECL={lr},BLKSIZE=0)")
    a("//*" + "-" * 64 + "*")
    a("//* NO SEED STEP: GLPOST CREATES GL ACCOUNTS ON FIRST USE, RATEMNT *")
    a("//* AND FXMNT SEED THEIR TABLES, SIGNON CREATES THE FIRST ADMIN.   *")
    a("//*" + "-" * 64 + "*")
    for line in L:
        assert len(line) <= 72, line
    open("jcl/CBSETUP.jcl", "w").write("\n".join(L) + "\n")


def proc():
    p = "jcl/CBPGM.prc"
    s = open(p).read()
    dds = "".join(f"//{n:<8} DD DSN=CBANK.PROD.{n}.KSDS,DISP=SHR\n" for n, *_ in KSDS)
    dds += "".join(f"//{n:<8} DD DSN=CBANK.PROD.{n},DISP=MOD\n" for n, *_ in SEQ)
    s = re.sub(r"(//STEPLIB  DD .*?\n)(?://\w+\s+DD DSN=CBANK\.PROD\..*?\n)+",
               lambda m: m.group(1) + dds, s, flags=re.S)
    open(p, "w").write(s)


setup()
proc()
print(f"jcl: {len(KSDS)} KSDS, {len(SEQ)} sequential files")
